# Data-owner tool: encrypts inputs for the FPGA and decrypts what it sends back.
import argparse
import re
import sys

import se

HEX_CT = re.compile(r"\b[0-9a-fA-F]{32}\b")


def ct_hex(ct):
    return f"{ct:032x}"


def ct_words(ct):
    return [(ct >> (32 * i)) & 0xFFFFFFFF for i in range(4)]


def write_header(values, path, name):
    lines = ["// Generated by host/owner.py: ciphertexts under the SE key, not plaintext.",
             "#include \"se.h\"", "",
             f"#define NUM_{name.upper()} {len(values)}", "",
             f"static const ct_t {name}[NUM_{name.upper()}] = {{"]
    for v in values:
        w = ", ".join(f"0x{x:08x}" for x in ct_words(se.encrypt(v)))
        lines.append(f"  {{{{{w}}}}},")
    lines.append("};")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    p = argparse.ArgumentParser(description="SE data-owner tool")
    sub = p.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("encrypt", help="print one ciphertext per value")
    e.add_argument("values", type=int, nargs="+")
    h = sub.add_parser("header", help="write the values as an encrypted C array")
    h.add_argument("values", type=int, nargs="+")
    h.add_argument("-o", "--out", required=True)
    h.add_argument("--name", default="inputs")
    d = sub.add_parser("decrypt", help="decrypt every 32-hex-digit ciphertext in the text")
    d.add_argument("cts", nargs="*", help="ciphertexts; reads stdin when empty")
    d.add_argument("-f", "--file")
    args = p.parse_args()

    if args.cmd == "encrypt":
        for v in args.values:
            print(ct_hex(se.encrypt(v)))
    elif args.cmd == "header":
        write_header(args.values, args.out, args.name)
    elif args.cmd == "decrypt":
        if args.cts:
            lines = args.cts
        else:
            lines = (open(args.file) if args.file else sys.stdin).read().splitlines()
        for line in lines:
            cts = HEX_CT.findall(line)
            if cts:
                plain = " ".join(str(se.decrypt(int(c, 16))) for c in cts)
                print(f"{line.strip()}  ->  {plain}")


if __name__ == "__main__":
    main()
